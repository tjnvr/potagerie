/** The drawn crop that stands for `crop` (`green_bean` or `green-bean`). */
export function drawingOf(crop: string): string {
  const id = crop.replaceAll("_", "-");
  if (DRAWN.has(id)) return id;
  return APPEARANCES[id]?.lookalike ?? "lettuce";
}
