#!/usr/bin/env python3
"""Converts the vegetable drawings of D01 (plants2.py) into front/src/lib/diorama/symboles.ts.

Run once, then commit the result:  python3 front/scripts/crop_symbols.py
The drawings are NOT redrawn here: plants2.plant() is called as it is, for the
6 vegetables of the V1 catalogue (S02) and the 4 stages (S03 section 3).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D01 = os.path.join(ROOT, "docs", "design", "POT-D01_key-screens_v1.2")
sys.path.insert(0, D01)
from plants2 import plant  # noqa: E402

# Catalogue id -> kind of plants2.py. Stage index of plants2: 0 sowing, 1 young shoot, 2 adult, 3 harvest.
CROPS = {
    "tomato": "tomato",
    "lettuce": "lettuce",
    "carrot": "carrot",
    "green-bean": "bean",
    "zucchini": "zucchini",
    "leek": "leek",
}
STAGES = ["sowing", "young_shoot", "adult", "harvest"]

# The plant is drawn around (0, 0), its foot on the soil. One common viewBox.
VIEWBOX = (-32, -66, 64, 76)

SORTIE = os.path.join(ROOT, "front", "src", "lib", "diorama", "symboles.ts")


def main() -> None:
    rows = [
        "// Generated by front/scripts/crop_symbols.py from POT-D01 plants2.py. Do not edit.",
        "// One drawing per vegetable and stage, centred on the foot of the plant.",
        "",
        f"export const VIEWBOX_SYMBOL = {list(VIEWBOX)} as const;",
        "",
        "/** Inner SVG of the symbol `plant-<crop>-<stade>`. */",
        "export const SYMBOLES: Record<string, string> = {",
    ]
    for crop, genre in CROPS.items():
        for i, stade in enumerate(STAGES):
            svg = plant(genre, i, 0, 0, 1.0)
            assert "`" not in svg and "${" not in svg
            rows.append(f'  "{crop}-{stade}": `{svg}`,')
    rows.append("};")
    rows.append("")
    with open(SORTIE, "w", encoding="utf-8") as f:
        f.write("\n".join(rows))
    print(f"{len(CROPS) * len(STAGES)} symbols written to {os.path.relpath(SORTIE, ROOT)}")


if __name__ == "__main__":
    main()
