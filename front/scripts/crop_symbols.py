#!/usr/bin/env python3
"""Generates front/src/lib/diorama/symboles.ts from the crop drawings of plant_art.py.

Run once, then commit the result:  python3 front/scripts/crop_symbols.py
plant_art.py builds on the drawing helpers of POT-D01 plants2.py. One drawing per
crop (see CROPS there) and per stage (S03 section 3): sowing, young shoot,
adult, harvest. The crops that have no drawing of their own borrow a look-alike
(front/src/lib/appearances.ts).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from plant_art import CROPS, HEIGHT, plant  # noqa: E402

STAGES = ["sowing", "young_shoot", "adult", "harvest"]

# The plant is drawn around (0, 0), its foot on the soil. One common viewBox.
VIEWBOX = (-32, -66, 64, 76)

OUTPUT = os.path.join(ROOT, "front", "src", "lib", "diorama", "symboles.ts")


def main() -> None:
    rows = [
        "// Generated by front/scripts/crop_symbols.py from plant_art.py. Do not edit.",
        "// One drawing per vegetable and stage, centred on the foot of the plant.",
        "",
        f"export const VIEWBOX_SYMBOL = {list(VIEWBOX)} as const;",
        "",
        "/** Height of each plant at its tallest, above its foot: frames the icons. */",
        "export const PLANT_HEIGHT: Record<string, number> = {",
    ]
    rows += [f'  "{crop}": {HEIGHT[crop]},' for crop in CROPS]
    rows += [
        "};",
        "",
        "/** Inner SVG of the symbol `plant-<crop>-<stage>`. */",
        "export const SYMBOLES: Record<string, string> = {",
    ]
    for crop in CROPS:
        for i, stage in enumerate(STAGES):
            svg = plant(crop, i)
            assert "`" not in svg and "${" not in svg
            rows.append(f'  "{crop}-{stage}": `{svg}`,')
    rows.append("};")
    rows.append("")
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write("\n".join(rows))
    print(f"{len(CROPS) * len(STAGES)} symbols written to {os.path.relpath(OUTPUT, ROOT)}")


if __name__ == "__main__":
    main()
