#!/usr/bin/env python3
"""Converts the vegetable drawings of D01 (plants2.py) into front/src/lib/diorama/symboles.ts.

Run once, then commit the result:  python3 front/scripts/symboles_legumes.py
The drawings are NOT redrawn here: plants2.plant() is called as it is, for the
6 vegetables of the V1 catalogue (S02) and the 4 stages (S03 section 3).
"""
import os
import sys

RACINE = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D01 = os.path.join(RACINE, "docs", "design", "POT-D01_ecrans-cles_v1.1")
sys.path.insert(0, D01)
from plants2 import plant  # noqa: E402

# Catalogue id -> kind of plants2.py. Stage index of plants2: 0 sowing, 1 young shoot, 2 adult, 3 harvest.
CULTURES = {
    "tomate": "tomate",
    "laitue": "laitue",
    "carotte": "carotte",
    "haricot-vert": "haricot",
    "courgette": "courgette",
    "poireau": "poireau",
}
STADES = ["sowing", "young_shoot", "adult", "harvest"]

# The plant is drawn around (0, 0), its foot on the soil. One common viewBox.
VIEWBOX = (-32, -66, 64, 76)

SORTIE = os.path.join(RACINE, "front", "src", "lib", "diorama", "symboles.ts")


def main() -> None:
    lignes = [
        "// Generated by front/scripts/symboles_legumes.py from POT-D01 plants2.py. Do not edit.",
        "// One drawing per vegetable and stage, centred on the foot of the plant.",
        "",
        f"export const VIEWBOX_SYMBOLE = {list(VIEWBOX)} as const;",
        "",
        "/** Inner SVG of the symbol `plante-<culture>-<stade>`. */",
        "export const SYMBOLES: Record<string, string> = {",
    ]
    for culture, genre in CULTURES.items():
        for i, stade in enumerate(STADES):
            svg = plant(genre, i, 0, 0, 1.0)
            assert "`" not in svg and "${" not in svg
            lignes.append(f'  "{culture}-{stade}": `{svg}`,')
    lignes.append("};")
    lignes.append("")
    with open(SORTIE, "w", encoding="utf-8") as f:
        f.write("\n".join(lignes))
    print(f"{len(CULTURES) * len(STADES)} symbols written to {os.path.relpath(SORTIE, RACINE)}")


if __name__ == "__main__":
    main()
