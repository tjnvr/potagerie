//! Potagerie, the Tauri app (S05 §3): commands, state and bindings.

mod command_names;
pub mod commands;
pub mod error;

use std::path::{Path, PathBuf};

use specta_typescript::Typescript;
use tauri::Manager;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

pub use command_names::COMMANDS;
use commands::AppState;

/// File name of the database in `app_data_dir` (S05 §3).
pub const DB_FILE: &str = "potagerie.db";

/// Where the TypeScript bindings are written, from the repository root.
pub fn bindings_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../front/src/lib/bindings.ts")
}

/// The commands and their types, for Tauri and for `bindings.ts`.
pub fn specta_builder<R: tauri::Runtime>() -> Builder<R> {
    Builder::<R>::new()
        // Commands resolve to { status: "ok", data } or { status: "error", error }.
        .error_handling(ErrorHandlingMode::Result)
        // One TypeScript type per Rust type, not one per serde direction.
        .disable_serde_phases()
        .commands(collect_commands![
            commands::catalogue,
            commands::vue_annee,
            commands::creer_terrain,
            commands::modifier_terrain,
            commands::creer_planche,
            commands::modifier_planche,
            commands::deplacer_planche,
            commands::series_depassant,
            commands::supprimer_planche,
            commands::creer_serie,
            commands::modifier_serie,
            commands::supprimer_serie,
            commands::decaler_serie,
            commands::apercu_serie,
            commands::cultures_de_saison,
            commands::creer_annotation,
            commands::modifier_annotation,
            commands::supprimer_annotation,
            commands::exporter_frise,
            commands::exporter_potager,
            commands::lire_import,
            commands::importer_potager,
            commands::vider_plan,
            commands::effacer_donnees,
        ])
}

/// Writes `bindings.ts`. Generated, never edited by hand (S05 §8).
pub fn export_bindings(builder: &Builder<tauri::Wry>, path: &Path) -> Result<(), String> {
    builder
        .export(
            Typescript::default().header(
                "// Generated by tauri-specta from src-tauri (make bindings). Do not edit.",
            ),
            path,
        )
        .map_err(|e| e.to_string())
}

/// The context from `tauri.conf.json`. Generated once: the macro embeds the
/// macOS Info.plist, which may only be defined once per crate.
fn context<R: tauri::Runtime>() -> tauri::Context<R> {
    tauri::generate_context!()
}

/// Starts the app.
pub fn run() {
    let builder = specta_builder::<tauri::Wry>();

    #[cfg(debug_assertions)]
    export_bindings(&builder, &bindings_path()).expect("failed to export bindings.ts");

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let dir = app.path().app_data_dir()?;
            std::fs::create_dir_all(&dir)?;
            let state = AppState::open(&dir.join(DB_FILE))?;
            app.manage(state);
            Ok(())
        })
        .run(context())
        .expect("error while running Potagerie");
}

